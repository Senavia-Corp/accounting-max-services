const BYTES = Uint8Array.from(atob(PNG_BASE64), (c) => c.charCodeAt(0));

// Ruta estatica: con output "static" esto se resuelve en el build y Vercel
// sirve dist/og-default.png como fichero. Las cabeceras quedan de contrato para
// el dia que deje de prerenderizarse.
export const GET: APIRoute = () =>
  new Response(BYTES, {
    headers: {
      "Content-Type": "image/png",
      "Content-Length": String(BYTES.byteLength),
      "Cache-Control": "public, max-age=31536000, immutable",
    },
  });
